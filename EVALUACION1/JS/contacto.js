// Manejador de cambio de tema con Bootstrap 5 y localStorage

const themeToggle = document.getElementById('themeToggle');
const htmlTag = document.documentElement;

// Al cargar la página, aplicar tema guardado
if (localStorage.getItem('theme') === 'dark') {
  htmlTag.setAttribute('data-bs-theme', 'dark');
  themeToggle.checked = true;
}

// Escuchar cambios en el switch
themeToggle.addEventListener('change', () => {
  const theme = themeToggle.checked ? 'dark' : 'light';
  htmlTag.setAttribute('data-bs-theme', theme);
  localStorage.setItem('theme', theme);
});

// Validación de campos de formulario
document.getElementById("contactForm").addEventListener("submit", function (event) {
  event.preventDefault();

  const name = document.getElementById("nombre").value.trim();
  const email = document.getElementById("correo").value.trim();
  const message = document.getElementById("message").value.trim();

  const errorMessage = document.getElementById("errorMessage");
  const successMessage = document.getElementById("successMessage");

  errorMessage.textContent = "";
  successMessage.textContent = "";

  if (name.length < 2) {
    errorMessage.textContent = "El nombre debe tener al menos 2 caracteres.";
    return;
  }

  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  if (!emailRegex.test(email)) {
    errorMessage.textContent = "Por favor, introduce un correo electrónico válido.";
    return;
  }
});
